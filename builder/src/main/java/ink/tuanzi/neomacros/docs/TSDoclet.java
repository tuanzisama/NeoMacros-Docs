package ink.tuanzi.neomacros.docs;

import jdk.javadoc.doclet.Doclet;
import jdk.javadoc.doclet.DocletEnvironment;
import jdk.javadoc.doclet.Reporter;

import javax.lang.model.SourceVersion;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Renders the TypeScript ambient definitions ({@code neomacros.d.ts}): one
 * {@code declare module '@neomacros/<name>'} block per module plus the
 * {@code declare const neo} global aggregate. Modules with
 * {@code global=false} appear as modules only; script-facing classes are
 * emitted as real class declarations (with their {@code extends} chain),
 * and event payload interfaces and referenced record types are emitted
 * alongside. The events facade additionally declares an explicit event-name
 * to payload-class map, and its subscription methods are generic over that
 * map so every event name resolves to the payload type it delivers.
 */
public class TSDoclet implements Doclet {

    /** Subscription methods of the events facade rendered as event-typed overloads. */
    private static final Set<String> EVENT_SUBSCRIPTION_METHODS =
            Set.of("on", "once", "waitFor", "waitForUntil", "onSync");

    private Reporter reporter;
    private Path outDir = Path.of("docs-dist");

    @Override
    public void init(Locale locale, Reporter reporter) {
        this.reporter = reporter;
    }

    @Override
    public String getName() {
        return "TSDoclet";
    }

    @Override
    public Set<? extends Doclet.Option> getSupportedOptions() {
        return Set.of(new Doclet.Option() {
            @Override
            public int getArgumentCount() {
                return 1;
            }

            @Override
            public String getDescription() {
                return "output directory for the generated TypeScript definitions";
            }

            @Override
            public Doclet.Option.Kind getKind() {
                return Doclet.Option.Kind.STANDARD;
            }

            @Override
            public List<String> getNames() {
                return List.of("-d");
            }

            @Override
            public String getParameters() {
                return "directory";
            }

            @Override
            public boolean process(String option, List<String> arguments) {
                outDir = Path.of(arguments.get(0));
                return true;
            }
        }, DocletSupport.passthroughOption("-tag"));
    }

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public boolean run(DocletEnvironment env) {
        ApiModel model = ModelExtractor.extract(env);
        Map<String, String> typeModules = buildTypeModules(model);
        Set<String> undeclared = undeclaredSignatureTypes(model, typeModules);
        for (String name : undeclared) {
            typeModules.putIfAbsent(name, "@neomacros/types");
        }
        Set<String> interfaceForms = interfaceFormClassNames(model, typeModules);
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by docs-builder from doc-api annotated facades. Do not edit.\n\n");
        for (ApiModel.ModuleModel module : model.modules()) {
            renderModule(sb, module, model, typeModules, interfaceForms);
        }
        renderStandaloneClasses(sb, model, typeModules, interfaceForms);
        renderEvents(sb, model, typeModules);
        renderUndeclaredStubs(sb, undeclared);
        renderGlobal(sb, model);

        for (String name : undeclared) {
            reporter.print(javax.tools.Diagnostic.Kind.WARNING, name
                    + ": referenced in signatures but never documented (@ApiClass or record); "
                    + "emitted as an opaque object type");
        }

        Path typesDir = outDir.resolve("types");
        try {
            Files.createDirectories(typesDir);
            Files.writeString(typesDir.resolve("neomacros.d.ts"), sb.toString(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            reporter.print(javax.tools.Diagnostic.Kind.ERROR,
                    "failed to write TypeScript definitions: " + e.getMessage());
            return false;
        }
        return true;
    }

    /**
     * Collects PascalCase names referenced in model signature strings that no
     * declared type (or TS built-in) backs: these come from annotations like
     * {@code @ApiType("Response")} pointing at types the doclet cannot see.
     */
    private static final Set<String> TS_BUILTIN_TYPES = Set.of("Promise", "Array", "Record");

    private static Set<String> undeclaredSignatureTypes(ApiModel model,
            Map<String, String> typeModules) {
        List<String> signatures = new ArrayList<>();
        for (ApiModel.ModuleModel module : model.modules()) {
            module.properties().forEach(p -> signatures.add(p.type()));
            module.methods().forEach(m -> {
                signatures.add(m.returnType());
                m.parameters().forEach(p -> signatures.add(p.type()));
            });
            for (ApiModel.ClassModel clazz : module.classes()) {
                clazz.properties().forEach(p -> signatures.add(p.type()));
                clazz.methods().forEach(m -> {
                    signatures.add(m.returnType());
                    m.parameters().forEach(p -> signatures.add(p.type()));
                });
            }
            module.referencedTypes().forEach(t -> t.fields().forEach(f -> signatures.add(f.type())));
        }
        for (ApiModel.ClassModel clazz : model.standaloneClasses()) {
            clazz.properties().forEach(p -> signatures.add(p.type()));
            clazz.methods().forEach(m -> {
                signatures.add(m.returnType());
                m.parameters().forEach(p -> signatures.add(p.type()));
            });
        }
        for (ApiModel.EventModel event : model.events()) {
            event.fields().forEach(f -> signatures.add(f.type()));
        }
        var matcher = java.util.regex.Pattern.compile("[A-Z][A-Za-z0-9_$]*").matcher("");
        Set<String> out = new java.util.TreeSet<>();
        for (String signature : signatures) {
            matcher.reset(signature);
            while (matcher.find()) {
                String name = matcher.group();
                if (!typeModules.containsKey(name) && !TS_BUILTIN_TYPES.contains(name)) {
                    out.add(name);
                }
            }
        }
        return out;
    }

    /**
     * Emits opaque object aliases for signature-referenced types the doclet
     * cannot document; annotating the source with {@code @ApiClass} (or
     * turning it into a record referenced from a signature) replaces the
     * stub with the real declaration.
     */
    private static void renderUndeclaredStubs(StringBuilder sb, Set<String> undeclared) {
        if (undeclared.isEmpty()) {
            return;
        }
        sb.append("declare module '@neomacros/types' {\n");
        sb.append("    /** Referenced in signatures but not yet documented with @ApiClass; opaque until annotated. */\n");
        for (String name : undeclared) {
            sb.append("    export type ").append(name).append(" = object;\n");
        }
        sb.append("}\n\n");
    }

    /**
     * Maps every declared type name to the {@code declare module} block it
     * lives in, so references from other blocks can be qualified with
     * import-type syntax (ambient module blocks are separate scopes).
     */
    private static Map<String, String> buildTypeModules(ApiModel model) {
        Map<String, String> out = new java.util.LinkedHashMap<>();
        for (ApiModel.ModuleModel module : model.modules()) {
            String block = "@neomacros/" + module.name();
            for (ApiModel.ClassModel clazz : module.classes()) {
                out.putIfAbsent(clazz.name(), block);
            }
            for (ApiModel.TypeModel type : module.referencedTypes()) {
                out.putIfAbsent(type.name(), block);
            }
        }
        String typesBlock = "@neomacros/types";
        for (ApiModel.ClassModel clazz : model.standaloneClasses()) {
            out.putIfAbsent(clazz.name(), typesBlock);
        }
        out.putIfAbsent("BaseEvent", typesBlock);
        for (ApiModel.EventModel event : model.events()) {
            out.putIfAbsent(DocletSupport.eventClassName(event.name()), typesBlock);
        }
        for (ApiModel.TypeModel type : model.eventReferencedTypes()) {
            out.putIfAbsent(type.name(), typesBlock);
        }
        return out;
    }

    /**
     * Qualifies references to types declared in another module block with
     * import-type syntax; names declared in the emitting block (or unknown
     * to the model, e.g. TS primitives) pass through untouched.
     */
    private static String qualifyTypes(String type, Map<String, String> typeModules,
            String currentBlock) {
        if (type == null || type.isEmpty() || typeModules.isEmpty()) {
            return type;
        }
        var matcher = java.util.regex.Pattern.compile("[A-Za-z_$][A-Za-z0-9_$]*").matcher(type);
        StringBuilder out = new StringBuilder();
        while (matcher.find()) {
            String block = typeModules.get(matcher.group());
            matcher.appendReplacement(out, java.util.regex.Matcher.quoteReplacement(
                    block != null && !block.equals(currentBlock)
                            ? "import('" + block + "')." + matcher.group()
                            : matcher.group()));
        }
        matcher.appendTail(out);
        return out.toString();
    }

    private static void renderModule(StringBuilder sb, ApiModel.ModuleModel module, ApiModel model,
            Map<String, String> typeModules, Set<String> interfaceForms) {
        String block = "@neomacros/" + module.name();
        sb.append("declare module '").append(block).append("' {\n");
        if (!module.doc().isEmpty()) {
            sb.append(indent(jsdoc(module.doc(), null, null), 4)).append("\n");
        }
        boolean eventsFacade = "events".equals(module.name());
        if (eventsFacade) {
            renderEventPayloadMap(sb, model);
        }
        sb.append("    export interface ").append(interfaceName(module)).append(" {\n");
        for (ApiModel.PropertyModel property : module.properties()) {
            renderProperty(sb, property, typeModules, block);
        }
        for (ApiModel.MethodModel method : module.methods()) {
            if (eventsFacade && EVENT_SUBSCRIPTION_METHODS.contains(method.name())) {
                renderEventSubscriptionMethod(sb, method, model, typeModules, block);
            } else {
                renderMethod(sb, method, typeModules, block);
            }
        }
        sb.append("    }\n");
        if (module.global()) {
            sb.append("    export const ").append(module.name()).append(": ")
                    .append(interfaceName(module)).append(";\n");
        }
        for (ApiModel.ClassModel clazz : module.classes()) {
            renderClassDeclaration(sb, clazz, typeModules, block, interfaceForms);
        }
        for (ApiModel.TypeModel type : module.referencedTypes()) {
            sb.append("    export interface ").append(type.name()).append(" {\n");
            for (ApiModel.ParameterModel field : type.fields()) {
                sb.append("        ").append(field.name()).append(": ")
                        .append(qualifyTypes(field.type(), typeModules, block)).append(";\n");
            }
            sb.append("    }\n");
        }
        sb.append("}\n\n");
    }

    /**
     * Renders the explicit event-name to payload-class map plus the
     * cancellable-name union inside the events facade module: every
     * built-in event name is declared with the payload type its handlers
     * receive, mirroring the typed-event-table style of eventemitter3.
     */
    private static void renderEventPayloadMap(StringBuilder sb, ApiModel model) {
        if (model.events().isEmpty()) {
            return;
        }
        sb.append("    /** The payload class delivered to handlers of each built-in event name. */\n");
        sb.append("    export interface EventPayloadMap {\n");
        for (ApiModel.EventModel event : model.events()) {
            sb.append("        '").append(event.name()).append("': import('@neomacros/types').")
                    .append(DocletSupport.eventClassName(event.name())).append(";\n");
        }
        sb.append("    }\n");
        List<String> cancellable = model.events().stream()
                .filter(ApiModel.EventModel::cancellable)
                .map(ApiModel.EventModel::name)
                .toList();
        if (!cancellable.isEmpty()) {
            sb.append("    /** Event names that accept synchronous, cancelling subscriptions. */\n");
            sb.append("    export type CancellableEvents =\n");
            for (int i = 0; i < cancellable.size(); i++) {
                sb.append("        '").append(cancellable.get(i)).append("'")
                        .append(i < cancellable.size() - 1 ? " |\n" : ";\n");
            }
        }
    }

    /**
     * Renders one events-facade subscription method as event-typed overloads:
     * the generic overload resolves the payload type for known event names,
     * the string overload keeps wildcard patterns ({@code domain:*},
     * {@code *}) and script-registered custom events accepted.
     */
    private static void renderEventSubscriptionMethod(StringBuilder sb,
            ApiModel.MethodModel method, ApiModel model, Map<String, String> typeModules,
            String block) {
        renderJsdoc(sb, method.doc(), method.since(), method.mc(),
                method.loader(), method.experimental(), method.permission());
        boolean hasEvents = !model.events().isEmpty();
        String base = "import('@neomacros/types').BaseEvent";
        switch (method.name()) {
            case "on", "once" -> {
                if (hasEvents) {
                    sb.append("        ").append(method.name())
                            .append("<E extends keyof EventPayloadMap>(name: E, ")
                            .append("handler: (event: EventPayloadMap[E]) => unknown): ")
                            .append(method.returnType()).append(";\n");
                }
                sb.append("        ").append(method.name())
                        .append("(name: string, handler: (event: ").append(base)
                        .append(") => unknown): ").append(method.returnType()).append(";\n");
            }
            case "onSync" -> {
                if (model.events().stream().anyMatch(ApiModel.EventModel::cancellable)) {
                    sb.append("        onSync<E extends CancellableEvents>(name: E, ")
                            .append("handler: (event: EventPayloadMap[E]) => unknown): void;\n");
                }
                sb.append("        onSync(name: string, handler: (event: ").append(base)
                        .append(") => unknown): void;\n");
            }
            case "waitFor" -> {
                if (hasEvents) {
                    sb.append("        waitFor<E extends keyof EventPayloadMap>(name: E): Promise<EventPayloadMap[E]>;\n");
                }
                sb.append("        waitFor(name: string): ").append(method.returnType()).append(";\n");
            }
            case "waitForUntil" -> {
                if (hasEvents) {
                    sb.append("        waitForUntil<E extends keyof EventPayloadMap>(name: E, ")
                            .append("filter: (event: EventPayloadMap[E]) => unknown, ")
                            .append("timeoutMillis: number): Promise<EventPayloadMap[E]>;\n");
                }
                sb.append("        waitForUntil(name: string, filter: (event: ").append(base)
                        .append(") => unknown, timeoutMillis: number): ")
                        .append(method.returnType()).append(";\n");
            }
            default -> renderMethod(sb, method, typeModules, block);
        }
    }

    /** Renders the JSDoc block combining description, badges, and markers. */
    private static void renderJsdoc(StringBuilder sb, String doc, String since, String mc,
                                    String loader, boolean experimental, String permission) {
        if (doc.isEmpty() && !experimental && permission == null) {
            return;
        }
        sb.append("        /** ");
        if (!doc.isEmpty()) {
            sb.append(doc.replaceAll("\\s+", " ").trim());
        }
        if (since != null) {
            sb.append(" @since ").append(since);
        }
        if (mc != null) {
            sb.append(" @mc ").append(mc);
        }
        if (experimental) {
            sb.append(" @experimental");
        }
        if (permission != null) {
            sb.append(" @requires permission '").append(permission).append("'");
        }
        sb.append(" */\n");
    }

    private static void renderProperty(StringBuilder sb, ApiModel.PropertyModel property,
            Map<String, String> typeModules, String block) {
        String description = property.doc().isEmpty() ? property.name() : property.doc();
        renderJsdoc(sb, description, property.since(), property.mc(),
                property.loader(), property.experimental(), property.permission());
        sb.append("        ").append(property.readOnly() ? "readonly " : "")
                .append(property.name()).append(": ")
                .append(qualifyTypes(property.type(), typeModules, block)).append(";\n");
    }

    private static void renderMethod(StringBuilder sb, ApiModel.MethodModel method,
            Map<String, String> typeModules, String block) {
        renderJsdoc(sb, method.doc(), method.since(), method.mc(),
                method.loader(), method.experimental(), method.permission());
        sb.append("        ").append(method.name()).append("(");
        for (int i = 0; i < method.parameters().size(); i++) {
            if (i > 0) {
                sb.append(", ");
            }
            ApiModel.ParameterModel parameter = method.parameters().get(i);
            sb.append(parameter.name()).append(parameter.optional() ? "?" : "")
                    .append(": ").append(qualifyTypes(parameter.type(), typeModules, block));
        }
        sb.append("): ").append(qualifyTypes(method.returnType(), typeModules, block)).append(";\n");
    }

    /**
     * Event payload classes: every payload dispatches as a frozen
     * {@code XxxEvent extends BaseEvent} instance, so the definitions are
     * real classes under the types module (instanceof works in scripts).
     * The class-name rule mirrors BindingRegistry.eventNameToClassName.
     * Record types referenced only from event fields are emitted alongside
     * so the payload definitions carry no dangling names.
     */
    private static void renderEvents(StringBuilder sb, ApiModel model,
            Map<String, String> typeModules) {
        if (model.events().isEmpty()) {
            return;
        }
        Set<String> moduleReferenced = new java.util.TreeSet<>();
        for (ApiModel.ModuleModel module : model.modules()) {
            for (ApiModel.TypeModel type : module.referencedTypes()) {
                moduleReferenced.add(type.name());
            }
        }
        String block = "@neomacros/types";
        sb.append("declare module '").append(block).append("' {").append("\n");
        sb.append("    export class BaseEvent {").append("\n");
        sb.append("        readonly type: string;").append("\n");
        sb.append("        readonly timestamp: number;").append("\n");
        sb.append("        readonly cancellable: boolean;").append("\n");
        sb.append("        toJSON(): object;").append("\n");
        sb.append("    }").append("\n");
        for (ApiModel.EventModel event : model.events()) {
            String name = DocletSupport.eventClassName(event.name());
            if (!event.doc().isEmpty()) {
                sb.append("    ").append(jsdoc(event.doc(), null, null)).append("\n");
            }
            sb.append("    export class ").append(name)
                    .append(" extends BaseEvent {").append("\n");
            for (ApiModel.ParameterModel field : event.fields()) {
                sb.append("        ").append(field.name())
                        .append(": ").append(qualifyTypes(field.type(), typeModules, block))
                        .append(";").append("\n");
            }
            sb.append("    }").append("\n");
        }
        for (ApiModel.TypeModel type : model.eventReferencedTypes()) {
            if (moduleReferenced.contains(type.name())) {
                continue;
            }
            sb.append("    export interface ").append(type.name()).append(" {\n");
            for (ApiModel.ParameterModel field : type.fields()) {
                sb.append("        ").append(field.name()).append(": ")
                        .append(qualifyTypes(field.type(), typeModules, block)).append(";\n");
            }
            sb.append("    }\n");
        }
        sb.append("}").append("\n").append("\n");
    }

    /** Standalone @ApiClass class declarations (types module supplement). */
    private static void renderStandaloneClasses(StringBuilder sb, ApiModel model,
            Map<String, String> typeModules, Set<String> interfaceForms) {
        if (model.standaloneClasses().isEmpty()) {
            return;
        }
        String block = "@neomacros/types";
        sb.append("declare module '").append(block).append("' {\n");
        for (ApiModel.ClassModel clazz : model.standaloneClasses()) {
            renderClassDeclaration(sb, clazz, typeModules, block, interfaceForms);
        }
        sb.append("}\n\n");
    }

    /**
     * Names of script-facing classes that must be emitted as interfaces: a
     * class whose superclass lives in another module block (or derives from
     * one, transitively) cannot keep the class {@code extends} form, because
     * {@code extends} consumes a value and an import type is a type.
     */
    private static Set<String> interfaceFormClassNames(ApiModel model,
            Map<String, String> typeModules) {
        Map<String, ApiModel.ClassModel> all = new java.util.LinkedHashMap<>();
        for (ApiModel.ModuleModel module : model.modules()) {
            for (ApiModel.ClassModel clazz : module.classes()) {
                all.putIfAbsent(clazz.name(), clazz);
            }
        }
        for (ApiModel.ClassModel clazz : model.standaloneClasses()) {
            all.putIfAbsent(clazz.name(), clazz);
        }
        Map<String, Boolean> memo = new java.util.LinkedHashMap<>();
        Set<String> out = new java.util.TreeSet<>();
        for (String name : all.keySet()) {
            if (resolveInterfaceForm(name, all, typeModules, memo, new java.util.LinkedHashSet<>())) {
                out.add(name);
            }
        }
        return out;
    }

    private static boolean resolveInterfaceForm(String name, Map<String, ApiModel.ClassModel> all,
            Map<String, String> typeModules, Map<String, Boolean> memo, Set<String> visiting) {
        Boolean memoized = memo.get(name);
        if (memoized != null) {
            return memoized;
        }
        ApiModel.ClassModel clazz = all.get(name);
        if (clazz == null || clazz.extendsName().isEmpty() || !visiting.add(name)) {
            memo.put(name, false);
            return false;
        }
        String parent = clazz.extendsName();
        String block = typeModules.get(name);
        String parentBlock = typeModules.get(parent);
        boolean result;
        if (parentBlock != null && block != null && !parentBlock.equals(block)) {
            result = true;
        } else {
            result = resolveInterfaceForm(parent, all, typeModules, memo, visiting);
        }
        memo.put(name, result);
        return result;
    }

    /**
     * Emits one script-facing class. Cross-module or interface-form
     * inheritance emits an interface (with an alias for the import type when
     * the superclass lives in another block); same-module class chains keep
     * the real class form.
     */
    private static void renderClassDeclaration(StringBuilder sb, ApiModel.ClassModel clazz,
            Map<String, String> typeModules, String block, Set<String> interfaceForms) {
        String parent = clazz.extendsName();
        String parentBlock = parent.isEmpty() ? null : typeModules.get(parent);
        boolean crossModuleParent = parentBlock != null && !parentBlock.equals(block);
        boolean interfaceForm = interfaceForms.contains(clazz.name());
        if (!interfaceForm) {
            sb.append("    ").append(jsdoc(clazz.doc(), null, null)).append("\n");
            sb.append("    export class ").append(clazz.name());
            if (!parent.isEmpty()) {
                sb.append(" extends ").append(parent);
            }
            sb.append(" {\n");
            renderClassMembers(sb, clazz, typeModules, block);
            sb.append("    }\n");
            return;
        }
        if (crossModuleParent) {
            sb.append("    type ").append(clazz.name()).append("Base = import('")
                    .append(parentBlock).append("').").append(parent).append(";\n");
            sb.append("    ").append(jsdoc(clazz.doc(), null, null)).append("\n");
            sb.append("    export interface ").append(clazz.name()).append(" extends ")
                    .append(clazz.name()).append("Base {\n");
        } else {
            sb.append("    ").append(jsdoc(clazz.doc(), null, null)).append("\n");
            sb.append("    export interface ").append(clazz.name()).append(" extends ")
                    .append(parent).append(" {\n");
        }
        renderClassMembers(sb, clazz, typeModules, block);
        sb.append("    }\n");
    }

    private static void renderClassMembers(StringBuilder sb, ApiModel.ClassModel clazz,
            Map<String, String> typeModules, String block) {
        for (ApiModel.PropertyModel property : clazz.properties()) {
            renderProperty(sb, property, typeModules, block);
        }
        for (ApiModel.MethodModel method : clazz.methods()) {
            renderMethod(sb, method, typeModules, block);
        }
    }

    /** The neo global aggregate listing modules reachable through the global channel. */
    private static void renderGlobal(StringBuilder sb, ApiModel model) {
        List<ApiModel.ModuleModel> globalModules = model.modules().stream()
                .filter(ApiModel.ModuleModel::global).toList();
        if (globalModules.isEmpty()) {
            return;
        }
        sb.append("declare const neo: {\n");
        for (ApiModel.ModuleModel module : globalModules) {
            sb.append("    ").append(module.name()).append(": import('@neomacros/")
                    .append(module.name()).append("').").append(interfaceName(module)).append(";\n");
        }
        sb.append("};\n");
    }

    /** Interface name for a module facade: PascalCase module name with the Api suffix. */
    private static String interfaceName(ApiModel.ModuleModel module) {
        return interfaceNameFromEvent(module.name()) + "Api";
    }

    /** Converts a dotted or colon-separated name to PascalCase. */
    private static String interfaceNameFromEvent(String name) {
        List<String> parts = new ArrayList<>();
        for (String part : name.split("[:.]")) {
            if (!part.isEmpty()) {
                parts.add(Character.toUpperCase(part.charAt(0)) + part.substring(1));
            }
        }
        return String.join("", parts);
    }

    /** Single-line JSDoc comment with optional since/availability tags. */
    private static String jsdoc(String doc, String since, String mc) {
        StringBuilder sb = new StringBuilder("/** ");
        sb.append(doc.replaceAll("\\s+", " ").trim());
        if (since != null) {
            sb.append(" @since ").append(since);
        }
        if (mc != null) {
            sb.append(" @mc ").append(mc);
        }
        sb.append(" */");
        return sb.toString();
    }

    private static String indent(String text, int spaces) {
        String pad = " ".repeat(spaces);
        return pad + text.replace("\n", "\n" + pad);
    }
}
